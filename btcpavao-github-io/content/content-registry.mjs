export function findContentByPath(pathname) {
  const normalized = pathname === "/" || pathname.endsWith("/") ? pathname : `${pathname}/`
  return contentRegistry.find((entry) => entry.path === normalized) ?? null
}

export function getPublishedContent() {
  return contentRegistry.filter((entry) => entry.status === "published")
}

export function getLanguageTarget(pathname, locale) {
  const entry = findContentByPath(pathname)
  if (!entry) return locale === "hr" ? coreHr : coreEn
  if (entry.locale === locale) return entry.path
  if (entry.translationPath) return entry.translationPath
  if (entry.section.startsWith("core")) return locale === "hr" ? coreHr : coreEn
  return locale === "hr" ? "/hr/" : "/"
}
